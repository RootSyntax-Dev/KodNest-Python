# int
a = 10
print(type(a), a)

# float
b = 45.54
print(type(b), b)

# bool
d = True
print(type(d), d)

# str
c = "Hello"   # '' or ""
print(type(c), c)


# list
f = [1, 2, 3]
print(type(f), f)

# tuple
g = (1, 2, 3)
print(type(g), g)

# set
h = {1, 2, 3}
print(type(h), h)

# dict
i = {"name": "Vinay", "age": 23}
print(type(i), i)

# complex
e = 10 + 20j
print(type(e), e)

# none
is_valid = None
print(type(is_valid), is_valid)


