# List slicing with negative and positive indices

a = [10, 20, 30, 40, 50, 60, 70, 80]
print(a[-2:-7:-2])  # [70, 50, 30]

a = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(a[-1:-9:-3])  # [9, 6, 3]

a = [10, 20, 30, 40, 50, 60]
print(a[-3::-2])  # [40, 20]

a = [1, 2, 3, 4, 5, 6, 7, 8]
print(a[-2:1:-2])  # [7, 5, 3]

a = [10, 20, 30, 40, 50, 60, 70]
print(a[-1:-8:-2])  # [70, 50, 30, 10]

a = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(a[-5:-1:2])  # [5, 7]

a = [10, 20, 30, 40, 50, 60, 70]
print(a[-6:-1:3])  # [20, 50]

a = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(a[-2:-8:-2])  # [8, 6, 4]

a = [10, 20, 30, 40, 50]
print(a[-1:-6:-1])  # [50, 40, 30, 20, 10]

a = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(a[-3:0:-1])  # [7, 6, 5, 4, 3, 2]

a = [10, 20, 30, 40, 50, 60, 70, 80]
print(a[1:-2:2])  # [20, 40, 60]

a = [1, 2, 3, 4, 5, 6, 7, 8]
print(a[-6:7:2])  # [3, 5, 7]

a = [10, 20, 30, 40, 50, 60, 70]
print(a[5:-6:-2])  # [60, 40, 20]

a = [1, 2, 3, 4, 5, 6, 7, 8, 9]
print(a[-7:8:3])  # [3, 6]

a = [10, 20, 30, 40, 50]
print(a[4:-5:-1])  # []

a = [1, 2, 3, 4, 5]
print(a[2:-1:-1])  # []

a = [10, 20, 30, 40, 50]
print(a[-5:1:1])  # [10]

a = [1, 2, 3, 4, 5, 6, 7]
print(a[5:-1:-1])  # []

a = [10, 20, 30, 40, 50, 60]
print(a[-2:0:2])  # []

